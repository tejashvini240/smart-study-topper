function makeTrackSubject(
  trackPrefix: string,
  subId: string,
  title: { en: string; te: string; hi: string },
  textbookName: { en: string; te: string; hi: string },
  diagram: DiagramType,
  chapters: Array<[string, string, string]>
): SubjectItem {
  return {
    id: `${trackPrefix}-${subId}`,
    title,
    textbookName,
    lessons: chapters.map(([en, te, hi], idx) =>
      buildLesson({
        id: `${trackPrefix}-${subId}-${idx + 1}`,
        num: idx + 1,
        en,
        te,
        hi,
        ref: `${textbookName.en} Ch.${idx + 1}`,
        diagram,
        summaryEn: `Comprehensive chapter notes for "${en}" from ${textbookName.en}. Includes core theorems, derivations, labeled conceptual diagrams, and high-yield exam questions.`,
        summaryTe: `${textbookName.te} లోని "${te}" పాఠం సమగ్ర వివరణ. ముఖ్య సూత్రాలు, నిర్వచనాలు, చిత్రాలు మరియు పరీక్షా ప్రశ్నలు ఇందులో ఉన్నాయి.`,
        summaryHi: `${textbookName.hi} के अध्याय "${hi}" के संपूर्ण नोट्स। मुख्य सिद्धांत, सूत्र, आरेख और परीक्षा के लिए महत्वपूर्ण प्रश्न शामिल हैं।`,
      })
    ),
  };
}

